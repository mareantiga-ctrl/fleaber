String clip(Object? v, [int n = 360]) {
  if (v is HttpHit) return clip(v.brief, n);
  final s = v is String ? v : jsonEncode(v);
  if (s.length <= n) return s;
  return '${s.substring(0, n)}…';
}

num? numOf(dynamic v) {
  if (v is num) return v;
  return num.tryParse('$v');
}

bool rpcDenied(HttpHit h) =>
    h.status == 401 ||
    h.status == 403 ||
    h.body.contains('42501') ||
    h.body.toLowerCase().contains('permission denied') ||
    h.body.toLowerCase().contains('not allowed') ||
    h.body.toLowerCase().contains('not_allowed');

bool refundSucceeded(HttpHit h) =>
    h.ok && (h.map?['ok'] == true || h.map?['refund_id'] != null) &&
    h.map?['skipped'] != true;

Map<String, String> loadEnvFile(String path) {
  final f = File(path);
  if (!f.existsSync()) return {};
  final out = <String, String>{};
  for (final raw in f.readAsLinesSync()) {
    final line = raw.trim();
    if (line.isEmpty || line.startsWith('#')) continue;
    final i = line.indexOf('=');
    if (i <= 0) continue;
    out[line.substring(0, i).trim()] = line.substring(i + 1).trim();
  }
  return out;
}

