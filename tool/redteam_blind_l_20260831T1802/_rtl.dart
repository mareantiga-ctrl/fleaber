  String? parseE2eOrderId(HttpHit paid) {
    final pm = paid.map ?? {};
    return (pm['order_id'] ??
            (pm['order'] is Map ? (pm['order'] as Map)['id'] : null))
        ?.toString();
  }

  String? parseE2eProductId(HttpHit paid) {
    return paid.map?['product_id']?.toString();
  }

  /// Stripe TEST → pago → mão → enviado → concluido (confirmação comprador).
  Future<String?> payAndComplete({String lens = 'L2'}) async {
    final paid = await e2e('setup_paid_order', {'initial_qty': 2});
    note('fixture.paid', 'setup_paid_order Stripe TEST', paid.brief, lens: lens);
    final oid = parseE2eOrderId(paid);
    final pid = parseE2eProductId(paid);
    if (pid != null) createdProductIds.add(pid);
    if (oid == null) return null;
    createdOrderIds.add(oid);
    if (pid != null) await ensureChat(pid);
    await rest('PATCH', 'orders?id=eq.$oid', jwt: sellerJwt, body: {
      'shipping_method': 'entrega em mão',
    });
    await rest(
      'PATCH',
      'orders?id=eq.$oid',
      jwt: sellerJwt,
      body: {'status': 'enviado'},
    );
    final conc = await rest(
      'PATCH',
      'orders?id=eq.$oid',
      jwt: buyerJwt,
      body: {'status': 'concluido'},
    );
    note('fixture.concluido', 'buyer confirma receção mão', conc.brief,
        lens: lens);
    return oid;
  }

  void note(String id, String title, Object? ev, {String? lens}) {
    notes.add({
      'id': id,
      if (lens != null) 'lens': lens,
      'title': title,
      'ev': ev is HttpHit ? ev.brief : ev,
    });
    stdout.writeln('NOTE $id ${lens ?? ''} $title ${clip(ev, 240)}');
  }

  void hold({
    required String id,
    required String lens,
    required String severity,
    required String title,
    required String actor,
    required String pre,
    required String repro,
    required Object? expected,
    required Object? obtained,
    bool proven = true,
    Map<String, Object?>? evidence,
