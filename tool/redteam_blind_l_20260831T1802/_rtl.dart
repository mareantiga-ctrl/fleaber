Future<List<HttpHit>> parallel(List<Future<HttpHit>> jobs) => Future.wait(jobs);

Future<void> dumpJson(String path, Object data) async {
  final f = File(path);
  await f.parent.create(recursive: true);
  await f.writeAsString(const JsonEncoder.withIndent('  ').convert(data));
}

String isoPast([Duration d = const Duration(hours: 49)]) =>
    DateTime.now().toUtc().subtract(d).toIso8601String();

String isoFuture([Duration d = const Duration(days: 30)]) =>
    DateTime.now().toUtc().add(d).toIso8601String();
