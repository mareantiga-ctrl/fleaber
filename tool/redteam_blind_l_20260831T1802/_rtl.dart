  Future<String?> createProduct({
    String? seller,
    String title = '$prefix-sku',
    int qty = 3,
    bool listed = true,
    double price = 8.5,
  }) async {
    final h = await rest('POST', 'products', service: true, body: {
      'seller_id': seller ?? sellerId,
      'title': title,
